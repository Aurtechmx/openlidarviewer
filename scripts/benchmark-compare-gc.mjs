#!/usr/bin/env node
/**
 * benchmark-compare-gc.mjs — put the GC-controlled ladders next to the default
 * ones and print the comparison as Markdown.
 *
 * WHY THIS EXISTS RATHER THAN A HAND-BUILT TABLE. The comparison in
 * `docs/benchmarks.md` is a claim about two experiments, and the tempting way to
 * write it is to read two `summary.md` files and type the numbers in. That is
 * the one thing the benchmark package refuses to do anywhere else: a
 * hand-entered figure has no provenance and drifts silently the moment either
 * run is repeated. Every number this prints is read out of an archived
 * `scaling/raw.json`, and re-running it against the same archives reproduces the
 * table character for character.
 *
 * WHY IT POOLS LADDERS BUT NOT COEFFICIENTS OF VARIATION. A single ladder is
 * five recorded runs per tier, which is a thin sample for a median on a machine
 * that is not idle, so the medians below pool every ladder of a mode. The
 * within-tier CV is NOT pooled: it is a statement about the spread inside one
 * process's five runs, and pooling four processes' runs into one CV would fold
 * the between-ladder drift into a number a reader takes to mean run-to-run
 * noise. It is reported as the range across ladders instead.
 *
 * Usage: node scripts/benchmark-compare-gc.mjs [benchmark-results dir]
 */

import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.argv[2] ?? 'benchmark-results';
const ARCHIVE = join(ROOT, 'archive');
const MIB = 1024 * 1024;

function median(xs) {
  const s = [...xs].sort((a, b) => a - b);
  const n = s.length;
  if (n === 0) return null;
  return n % 2 ? s[(n - 1) / 2] : (s[n / 2 - 1] + s[n / 2]) / 2;
}

/**
 * Sample coefficient of variation, n−1 in the denominator.
 *
 * Undefined below two runs, and returned as null rather than 0 — a zero here
 * would read as "perfectly repeatable", which is the opposite of "not enough
 * runs to say".
 */
function cv(xs) {
  if (xs.length < 2) return null;
  const mean = xs.reduce((a, b) => a + b, 0) / xs.length;
  if (mean === 0) return null;
  const variance = xs.reduce((a, b) => a + (b - mean) ** 2, 0) / (xs.length - 1);
  return Math.sqrt(variance) / mean;
}

if (!existsSync(ARCHIVE)) {
  console.error(`no archive directory at ${ARCHIVE} — run \`npm run benchmark:scaling\` first`);
  process.exit(1);
}

/** One archived ladder, reduced to what the comparison needs. */
const ladders = [];
for (const name of readdirSync(ARCHIVE).sort()) {
  const dir = join(ARCHIVE, name);
  const rawPath = join(dir, 'scaling', 'raw.json');
  if (!existsSync(rawPath)) continue;
  const manifest = JSON.parse(readFileSync(join(dir, 'manifest.json'), 'utf8'));
  const raw = JSON.parse(readFileSync(rawPath, 'utf8'));
  // Keyed on what the runs OBSERVED, not on what was requested: a ladder whose
  // flag failed to arrive belongs in the default column no matter what the
  // operator typed, and 'mixed' belongs in neither.
  const observed = manifest.forcedGc?.observedInRuns ?? 'none';
  ladders.push({
    name,
    observed,
    loadAverage: manifest.loadAverage?.status === 'captured' ? manifest.loadAverage.value : 'unavailable',
    startedAtUtc: manifest.startedAtUtc,
    tiers: raw.tiers.map((t) => ({
      id: t.tier.id,
      status: t.status,
      analysisMs: t.runs.map((r) => r.observation.durations.analysisMs),
      pointsPerSecond: t.runs.map((r) => r.observation.durations.pointsPerSecond),
      peakRssBytes: t.runs.map((r) => r.observation.memory.peakRssBytes),
    })),
  });
}

const MODES = [
  { key: 'none', label: 'default (GC uncontrolled)' },
  { key: 'all', label: 'GC controlled (--expose-gc)' },
];

const out = [];
out.push('<!-- generated by scripts/benchmark-compare-gc.mjs; do not hand-edit -->');
out.push('');

for (const mode of MODES) {
  const mine = ladders.filter((l) => l.observed === mode.key);
  out.push(`### ${mode.label}`);
  out.push('');
  if (mine.length === 0) {
    out.push('No ladder in this directory was measured in this mode.');
    out.push('');
    continue;
  }
  out.push(`${mine.length} ladder${mine.length === 1 ? '' : 's'}, ${mine[0].tiers[0].analysisMs.length} recorded runs per tier each:`);
  out.push('');
  for (const l of mine) out.push(`- \`${l.name}\` — load average ${l.loadAverage}`);
  out.push('');
  out.push('| tier | median analysis (ms) | median points/s | peak RSS median (MiB) | peak RSS max (MiB) | within-tier CV of analysis, per ladder |');
  out.push('| --- | --- | --- | --- | --- | --- |');
  const tierIds = mine[0].tiers.map((t) => t.id);
  for (const id of tierIds) {
    const per = mine.map((l) => l.tiers.find((t) => t.id === id)).filter(Boolean);
    const analysis = per.flatMap((t) => t.analysisMs).filter((v) => v !== null);
    const pps = per.flatMap((t) => t.pointsPerSecond).filter((v) => v !== null);
    const rss = per.flatMap((t) => t.peakRssBytes).filter((v) => v !== null);
    const cvs = per.map((t) => cv(t.analysisMs.filter((v) => v !== null))).filter((v) => v !== null);
    out.push(
      `| ${id} | ${median(analysis).toFixed(0)} | ${median(pps).toFixed(0)} | ${(median(rss) / MIB).toFixed(0)} | ${(Math.max(...rss) / MIB).toFixed(0)} | ${Math.min(...cvs).toFixed(3)}–${Math.max(...cvs).toFixed(3)} |`,
    );
  }
  out.push('');
  // The one derived quantity the whole comparison turns on, computed per ladder
  // rather than off the pooled medians: the question is whether the falling limb
  // is present in each experiment, not whether it survives averaging.
  const limbs = mine.map((l) => {
    const peak = median(l.tiers.find((t) => t.id === '250k').pointsPerSecond);
    const top = median(l.tiers.find((t) => t.id === '1m').pointsPerSecond);
    return ((peak - top) / peak) * 100;
  });
  out.push(
    `Falling limb, 1M throughput below the 250k tier, one figure per ladder: ${limbs.map((v) => `${v.toFixed(1)} %`).join(', ')}.`,
  );
  out.push('');
}

console.log(out.join('\n'));
