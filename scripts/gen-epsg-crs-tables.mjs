#!/usr/bin/env node
/**
 * gen-epsg-crs-tables.mjs: regenerates the EPSG tables the LAS and ASCII
 * writers read to decide what kind of CRS a code names and which OGC WKT
 * describes it.
 *
 *   src/convert/geographicEpsgCodes.ts  geographic 2D and 3D codes, and the
 *                                       ones whose angular unit is the grad
 *   src/convert/epsgCrsKindTable.ts     projected, geocentric, compound,
 *                                       vertical and engineering codes, and
 *                                       the projected codes not in metres
 *   src/io/epsgWktTable.ts              verified WKT1 for the codes OLV can
 *                                       derive (see src/io/epsgWkt.ts)
 *
 * Inputs: PROJ's proj.db (read with the sqlite3 CLI) and `projinfo`. The
 * database is the first proj.db on `projinfo --searchpaths`, or PROJ_DB when
 * set. Every WKT the table can produce is rebuilt here and compared with
 * `projinfo EPSG:<code> -o WKT1_GDAL`; the script stops on the first
 * difference, so a committed table only holds strings PROJ produced.
 *
 * Run: node scripts/gen-epsg-crs-tables.mjs
 */

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function findDb() {
  if (process.env.PROJ_DB) return process.env.PROJ_DB;
  const paths = execFileSync('projinfo', ['--searchpaths'], { encoding: 'utf8' }).split('\n').filter(Boolean);
  for (const p of paths) if (existsSync(join(p, 'proj.db'))) return join(p, 'proj.db');
  throw new Error('proj.db not found; set PROJ_DB');
}

const DB = findDb();
const sql = (q) => execFileSync('sqlite3', [DB, q], { encoding: 'utf8' }).split('\n').filter(Boolean);
const meta = Object.fromEntries(sql("select key, value from metadata").map((l) => l.split('|')));
const EPSG_VERSION = meta['EPSG.VERSION'];
const EPSG_DATE = meta['EPSG.DATE'];
const PROJ_VERSION = meta['PROJ.VERSION'];

const codes = (q) => sql(q).map(Number).sort((a, b) => a - b);

/** Fold sorted integers into flattened inclusive ranges. */
function ranges(list) {
  const out = [];
  for (const c of list) {
    if (out.length > 0 && out[out.length - 1] === c - 1) out[out.length - 1] = c;
    else out.push(c, c);
  }
  return out;
}

function formatRanges(name, doc, list) {
  const r = ranges(list);
  const pairs = [];
  for (let i = 0; i < r.length; i += 2) pairs.push(`${r[i]},${r[i + 1]}`);
  const lines = [];
  for (let i = 0; i < pairs.length; i += 8) lines.push(`  ${pairs.slice(i, i + 8).join(', ')},`);
  return `/** ${doc} ${list.length} codes in ${r.length / 2} ranges. */\nexport const ${name}: readonly number[] = [\n${lines.join('\n')}\n];\n`;
}

const AXIS_UNIT = (table, where) =>
  `select cast(c.code as int), a.uom_code from ${table} c join axis a
     on a.coordinate_system_auth_name = c.coordinate_system_auth_name
    and a.coordinate_system_code = c.coordinate_system_code
    and a.coordinate_system_order = 1
  where c.auth_name = 'EPSG' ${where} order by 1`;

const geographic = codes("select cast(code as int) from geodetic_crs where auth_name='EPSG' and type in ('geographic 2D','geographic 3D')");
const geographicGrad = sql(AXIS_UNIT('geodetic_crs', "and c.type in ('geographic 2D','geographic 3D')"))
  .map((l) => l.split('|'))
  .filter(([, u]) => u === '9105')
  .map(([c]) => Number(c));
const projected = codes("select cast(code as int) from projected_crs where auth_name='EPSG'");
const geocentric = codes("select cast(code as int) from geodetic_crs where auth_name='EPSG' and type='geocentric'");
const compound = codes("select cast(code as int) from compound_crs where auth_name='EPSG'");
const vertical = codes("select cast(code as int) from vertical_crs where auth_name='EPSG'");
const engineering = codes("select cast(code as int) from engineering_crs where auth_name='EPSG'");
const projectedUnits = sql(AXIS_UNIT('projected_crs', '')).map((l) => l.split('|').map(Number));
const byUnit = (u) => projectedUnits.filter(([, unit]) => unit === u).map(([c]) => c);
const otherUnit = projectedUnits.filter(([, unit]) => ![9001, 9002, 9003].includes(unit)).map(([c]) => c);

const source = `the EPSG dataset ${EPSG_VERSION} (${EPSG_DATE}) as shipped in PROJ ${PROJ_VERSION}'s proj.db`;
const banner = (what) =>
  `/**\n * ${what}\n *\n * Source: the EPSG dataset ${EPSG_VERSION} (${EPSG_DATE}) as shipped in PROJ\n * ${PROJ_VERSION}'s proj.db, deprecated codes included (files written before a\n * code was deprecated still carry it). Generated by\n * scripts/gen-epsg-crs-tables.mjs; do not edit by hand.\n */\n`;

writeFileSync(
  join(ROOT, 'src/convert/geographicEpsgCodes.ts'),
  banner('geographicEpsgCodes.ts: the EPSG codes whose CRS is geographic (2D or 3D,\n * longitude/latitude in angular units).') +
    `\n/** The EPSG dataset version these tables were generated from. */\nexport const EPSG_DATASET_VERSION = '${EPSG_VERSION}';\n\n` +
    formatRanges('GEOGRAPHIC_EPSG_RANGES', 'Geographic 2D and 3D CRS codes, flattened inclusive [first, last] pairs.', geographic) +
    '\n' +
    formatRanges('GEOGRAPHIC_GRAD_EPSG_RANGES', 'Geographic CRS codes whose angular unit is the grad rather than the degree.', geographicGrad),
);

writeFileSync(
  join(ROOT, 'src/convert/epsgCrsKindTable.ts'),
  banner('epsgCrsKindTable.ts: the EPSG codes of every CRS kind other than geographic,\n * and the projected codes whose linear unit is not the metre.') +
    '\n' +
    [
      formatRanges('PROJECTED_EPSG_RANGES', 'Projected CRS codes.', projected),
      formatRanges('GEOCENTRIC_EPSG_RANGES', 'Geocentric (ECEF) CRS codes.', geocentric),
      formatRanges('COMPOUND_EPSG_RANGES', 'Compound (horizontal + vertical) CRS codes.', compound),
      formatRanges('VERTICAL_EPSG_RANGES', 'Vertical CRS codes.', vertical),
      formatRanges('ENGINEERING_EPSG_RANGES', 'Engineering CRS codes.', engineering),
      formatRanges('PROJECTED_FOOT_EPSG_RANGES', 'Projected CRS codes in the international foot (EPSG 9002).', byUnit(9002)),
      formatRanges('PROJECTED_US_FOOT_EPSG_RANGES', 'Projected CRS codes in the US survey foot (EPSG 9003).', byUnit(9003)),
      formatRanges('PROJECTED_OTHER_UNIT_EPSG_RANGES', 'Projected CRS codes in a linear unit other than the metre or either foot.', otherUnit),
    ].join('\n'),
);

// ── WKT ───────────────────────────────────────────────────────────────────

const wktCache = new Map();
function projWkt(id) {
  if (!wktCache.has(id)) {
    const out = execFileSync('projinfo', [id, '-o', 'WKT1_GDAL', '--single-line', '-q'], { encoding: 'utf8' }).trim();
    wktCache.set(id, out);
  }
  return wktCache.get(id);
}

/** UTM-pattern families: one base geographic CRS, a name pattern, and a zone range. */
const UTM_FAMILIES = [
  { first: 32601, last: 32660, zoneBase: 32600, south: false, base: 4326, name: 'WGS 84 / UTM zone {z}N' },
  { first: 32701, last: 32760, zoneBase: 32700, south: true, base: 4326, name: 'WGS 84 / UTM zone {z}S' },
  { first: 26901, last: 26923, zoneBase: 26900, south: false, base: 4269, name: 'NAD83 / UTM zone {z}N' },
  { first: 6330, last: 6348, zoneBase: 6329, south: false, base: 6318, name: 'NAD83(2011) / UTM zone {z}N' },
  { first: 26701, last: 26722, zoneBase: 26700, south: false, base: 4267, name: 'NAD27 / UTM zone {z}N' },
  { first: 25828, last: 25838, zoneBase: 25800, south: false, base: 4258, name: 'ETRS89 / UTM zone {z}N' },
  { first: 28348, last: 28358, zoneBase: 28300, south: true, base: 4283, name: 'GDA94 / MGA zone {z}' },
  { first: 7846, last: 7859, zoneBase: 7800, south: true, base: 7844, name: 'GDA2020 / MGA zone {z}' },
];

/** Codes stored whole: the built-in registry's named CRS (src/convert/epsg.ts STATIC_DEFS) and the UTM bases. */
const STATIC_CODES = [
  4326, 4269, 4267, 4258, 4283, 7844, 4167, 4490, 6318, 4978,
  3857, 3395, 27700, 2154, 2056, 2193, 3035, 3577, 5070, 5514,
];

const demSrc = readFileSync(join(ROOT, 'src/terrain/export/demGeoTiff.ts'), 'utf8');
const vtable = demSrc.slice(demSrc.indexOf('export const VERTICAL_CRS_UNITS'));
const verticalCodes = [...vtable.slice(0, vtable.indexOf('};')).matchAll(/^\s+(\d+): \{/gm)].map((m) => Number(m[1]));

const staticWkt = Object.fromEntries(STATIC_CODES.map((c) => [c, projWkt(`EPSG:${c}`)]));
const vertWkt = Object.fromEntries(verticalCodes.map((c) => [c, projWkt(`EPSG:${c}`)]));
for (const [c, w] of Object.entries(vertWkt)) {
  if (!w.startsWith('VERT_CS[')) throw new Error(`EPSG:${c} is not a VERT_CS: ${w.slice(0, 40)}`);
}

// The template src/io/epsgWkt.ts assembles; checked here against projinfo for
// every zone so the committed families are exact.
function utmWkt(f, code) {
  const zone = code - f.zoneBase;
  const name = f.name.replace('{z}', String(zone));
  return (
    `PROJCS["${name}",${staticWkt[f.base]},PROJECTION["Transverse_Mercator"],` +
    `PARAMETER["latitude_of_origin",0],PARAMETER["central_meridian",${6 * zone - 183}],` +
    `PARAMETER["scale_factor",0.9996],PARAMETER["false_easting",500000],` +
    `PARAMETER["false_northing",${f.south ? 10000000 : 0}],UNIT["metre",1,AUTHORITY["EPSG","9001"]],` +
    `AXIS["Easting",EAST],AXIS["Northing",NORTH],AUTHORITY["EPSG","${code}"]]`
  );
}
// A zone the template does not reproduce (a deprecated code, whose name PROJ
// suffixes with "(deprecated)") is stored whole instead; STATIC_WKT is
// consulted first, so the family never produces it.
let checked = 0;
const storedWhole = [];
for (const f of UTM_FAMILIES) {
  for (let c = f.first; c <= f.last; c++) {
    const want = projWkt(`EPSG:${c}`);
    if (!want.startsWith('PROJCS[')) throw new Error(`EPSG:${c} is not a PROJCS: ${want.slice(0, 40)}`);
    if (utmWkt(f, c) !== want) {
      staticWkt[c] = want;
      storedWhole.push(c);
    }
    checked++;
  }
}

const q = (s) => JSON.stringify(s);
const recordLines = (obj) =>
  Object.entries(obj)
    .map(([c, w]) => `  ${c}:\n    ${q(w)},`)
    .join('\n');

writeFileSync(
  join(ROOT, 'src/io/epsgWktTable.ts'),
  `/**
 * epsgWktTable.ts: OGC WKT1 (GDAL flavour) for the EPSG codes OLV can write
 * as a LAS 1.4 coordinate-system record.
 *
 * Every string here is \`projinfo EPSG:<code> -o WKT1_GDAL --single-line\` from
 * PROJ ${PROJ_VERSION} with ${source.replace(/ as shipped.*/, '')}. The UTM families
 * are assembled from their base geographic CRS by src/io/epsgWkt.ts; the
 * generator rebuilt all ${checked} of those codes and compared each with projinfo
 * before writing this file. Generated by scripts/gen-epsg-crs-tables.mjs; do
 * not edit by hand.
 */

/** The EPSG dataset version the WKT came from. */
export const EPSG_WKT_DATASET_VERSION = '${EPSG_VERSION}';

/** A UTM-pattern family: codes first..last are zones (code - zoneBase) on \`base\`. */
export interface UtmFamily {
  readonly first: number;
  readonly last: number;
  readonly zoneBase: number;
  readonly south: boolean;
  readonly base: number;
  /** CRS name with \`{z}\` for the zone number. */
  readonly name: string;
}

export const UTM_FAMILIES: readonly UtmFamily[] = [
${UTM_FAMILIES.map((f) => `  { first: ${f.first}, last: ${f.last}, zoneBase: ${f.zoneBase}, south: ${f.south}, base: ${f.base}, name: ${q(f.name)} },`).join('\n')}
];

/** Horizontal (and the one geocentric) CRS stored whole, by EPSG code. */
export const STATIC_WKT: Readonly<Record<number, string>> = {
${recordLines(staticWkt)}
};

/** VERT_CS for the vertical codes the LAS vertical GeoKeys can carry (VERTICAL_CRS_UNITS). */
export const VERT_CS_WKT: Readonly<Record<number, string>> = {
${recordLines(vertWkt)}
};
`,
);

console.log(`EPSG ${EPSG_VERSION} (${EPSG_DATE}), PROJ ${PROJ_VERSION}`);
console.log(`geographic ${geographic.length} (grad ${geographicGrad.length}), projected ${projected.length}, geocentric ${geocentric.length}, compound ${compound.length}, vertical ${vertical.length}, engineering ${engineering.length}`);
console.log(`stored whole (template mismatch): ${storedWhole.join(', ') || 'none'}`);
console.log(`WKT: ${STATIC_CODES.length} static, ${verticalCodes.length} vertical, ${checked} UTM codes checked against projinfo`);
