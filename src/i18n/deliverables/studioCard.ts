/**
 * studioCard.ts: the words of the Studio image card in each export language.
 *
 * The card's rows are built by seven exporters and the shared base rows, in
 * English. Rather than thread a language through every exporter, the card is
 * translated as it is drawn: exact English text is looked up here, and text
 * with figures in it is matched against the templates below. English is never
 * looked up, so an English card is unchanged. A test runs every exporter and
 * fails if a label or a value it can print has no translation.
 *
 * Sentences other modules own are imported, not copied, so there is one
 * English wording. ASPRS class names inside a class-filter note stay in
 * English, as the standard names them.
 */
